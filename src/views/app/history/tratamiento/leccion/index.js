const PoseDetectionScreen = () => {
  const theme = useTheme();
  const webcamRef = useRef(null); // Referencia a la webcam
  const canvasRef = useRef(null); // Referencia al canvas para dibujar
  const canvasGuiaRef = useRef(null); // Referencia al canvas para dibujar
  const [status, setStatus] = useState('Inicializando...');
  const [videoDevices, setVideoDevices] = useState([]); // Lista de cámaras disponibles
  const [selectedDeviceId, setSelectedDeviceId] = useState(''); // Cámara seleccionada
  const [isDetecting, setIsDetecting] = useState(false); // Estado de detección
  const [viewCameraList, setViewCameraList] = useState(false);
  const websocketRef = useRef(null); // Referencia al WebSocket
  const [isLoading, setIsLoading] = useState(false); // Estado de carga de detección

  // Stepper state
  const [activeStep, setActiveStep] = useState(0);

  // Stepper steps
  const steps = [''];
  const [puntosGuia] = useState(points);

  useEffect(() => {
    let intervalId;
    let currentIndex = 0;

    const updatePoseGuia = () => {
      // Verificar que haya puntos disponibles
      if (puntosGuia[currentIndex]) {
        drawPoseGuia(puntosGuia[currentIndex].pose.keypoints);

        // Incrementar el índice, volver a 0 si llega al final
        currentIndex = (currentIndex + 1) % puntosGuia.length;
      }
    };

    // Comenzar inmediatamente y luego cada segundo
    updatePoseGuia();
    intervalId = setInterval(updatePoseGuia, 1000);

    // Limpiar el intervalo cuando el componente se desmonte
    return () => {
      if (intervalId) {
        clearInterval(intervalId);
      }
    };
  }, [puntosGuia]); // Añadir puntosGuia como dependencia

  useEffect(() => {
    const getDevices = async () => {
      try {
        const devices = await navigator.mediaDevices.enumerateDevices();
        const videoInputDevices = devices.filter((device) => device.kind === 'videoinput');
        setVideoDevices(videoInputDevices);
        if (videoInputDevices.length > 0) {
          setSelectedDeviceId(videoInputDevices[0].deviceId); // Seleccionar la primera cámara
        }
      } catch (err) {
        console.error('Error al enumerar dispositivos:', err);
      }
    };

    getDevices();
  }, []);

  useEffect(() => {
    // Conectar al servidor Socket.IO
    websocketRef.current = io(SOCKET_SERVER_URL, {
      secure: true,
      rejectUnauthorized: false, // Solo para desarrollo, NO usar en producción
      transports: ['websocket'] // Forzar websocket
    });

    websocketRef.current.on('connect', () => {
      console.log('Conectado al servidor Socket.IO');
    });

    websocketRef.current.on('detection', (receivedData) => {
      try {
        console.log('Datos recibidos:', receivedData);
        drawPose(receivedData.keypoints);
        setStatus(`Puntos clave detectados: ${receivedData.keypoints.length}`);
        setIsLoading(false);
      } catch (err) {
        console.error('Error al procesar el mensaje del servidor:', err);
      }
    });

    websocketRef.current.on('disconnect', () => {
      console.log('Desconectado del servidor Socket.IO');
    });

    return () => {
      if (websocketRef.current) {
        websocketRef.current.disconnect();
      }
    };
  }, []);

  useEffect(() => {
    let interval = null;

    if (isDetecting) {
      setIsLoading(true);
      setStatus('Enviando fotogramas para detección...');
      console.log('Enviando fotogramas para detección...');

      interval = setInterval(() => {
        if (webcamRef.current && webcamRef.current.getScreenshot()) {
          const imageSrc = webcamRef.current.getScreenshot();
          if (imageSrc) {
            // Cambio clave: usar emit en lugar de send
            if (websocketRef.current && websocketRef.current.connected) {
              websocketRef.current.emit('detection', {
                type: 'detection',
                image: imageSrc
              });
            } else {
              console.error('Socket no está conectado');
            }
          }
        }
      }, 200); // Enviar cada 100ms (10 fps). Ajusta según tus necesidades y capacidades del servidor.
    }

    return () => {
      if (interval) clearInterval(interval);
    };
  }, [isDetecting]);

  const handleCameraChange = (deviceId) => {
    setSelectedDeviceId(deviceId);
    setStatus('Cambiando de cámara...');
    // Esperar un breve período para que la cámara se actualice
    setTimeout(() => {
      setStatus('Cámara cambiada. Iniciando detección de poses...');
      if (isDetecting) {
        // Reiniciar detección para la nueva cámara
        setIsDetecting(false);
        setTimeout(() => {
          setIsDetecting(true);
        }, 500);
      }
    }, 1000);
  };

  const toggleDetection = () => {
    if (isDetecting) {
      setIsDetecting(false);
      setStatus('Detección pausada.');
      clearCanvas();
    } else {
      setIsDetecting(true);
      setIsLoading(true);
      setStatus('Iniciando detección de poses...');
    }
  };

  const clearCanvas = () => {
    const canvas = canvasRef.current;
    if (canvas) {
      const ctx = canvas.getContext('2d');
      ctx.clearRect(0, 0, canvas.width, canvas.height); // Limpia el canvas
    }
  };

  const drawPose = (keypoints) => {
    const canvas = canvasRef.current;
    const webcam = webcamRef.current;

    if (!canvas || !webcam || !keypoints) return;

    const ctx = canvas.getContext('2d');
    const video = webcam.video;

    // Configurar tamaño del canvas para que coincida con el video
    canvas.width = video.videoWidth;
    canvas.height = video.videoHeight;

    // Limpia el canvas
    ctx.clearRect(0, 0, canvas.width, canvas.height);

    // Escalar keypoints al tamaño del video/canvas
    keypoints.forEach((kp) => {
      if (kp.score > 0.5) {
        // Filtrar puntos con baja confianza
        const x = kp.x * canvas.width; // Escalar x
        const y = kp.y * canvas.height; // Escalar y

        // Dibujar punto
        ctx.beginPath();
        ctx.arc(x, y, 5, 0, 2 * Math.PI);
        ctx.fillStyle = 'red';
        ctx.fill();
      }
    });

    // Dibujar conexiones entre keypoints
    const connections = [
      [0, 1],
      [0, 2],
      [1, 3],
      [2, 4],
      [0, 5],
      [0, 6],
      [5, 7],
      [7, 9],
      [6, 8],
      [8, 10],
      [5, 6],
      [5, 11],
      [6, 12],
      [11, 12],
      [11, 13],
      [13, 15],
      [12, 14],
      [14, 16]
    ];

    connections.forEach(([startIdx, endIdx]) => {
      const start = keypoints[startIdx];
      const end = keypoints[endIdx];

      if (start.score > 0.5 && end.score > 0.5) {
        ctx.beginPath();
        ctx.moveTo(start.x * canvas.width, start.y * canvas.height); // Escalar inicio
        ctx.lineTo(end.x * canvas.width, end.y * canvas.height); // Escalar fin
        ctx.strokeStyle = 'green';
        ctx.lineWidth = 2;
        ctx.stroke();
      }
    });
  };
  const drawPoseGuia = (keypoints) => {
    const canvas = canvasGuiaRef.current;
    if (!canvas || !keypoints) return;

    const ctx = canvas.getContext('2d');

    // Set canvas size explicitly
    canvas.width = 120;
    canvas.height = 240;

    // Limpia el canvas
    ctx.clearRect(0, 0, canvas.width, canvas.height);

    // Normalizar coordenadas primero
    const normalizeCoords = (keypoints) => {
      const xs = keypoints.map((kp) => kp.x);
      const ys = keypoints.map((kp) => kp.y);
      const minX = Math.min(...xs);
      const maxX = Math.max(...xs);
      const minY = Math.min(...ys);
      const maxY = Math.max(...ys);

      return keypoints.map((kp) => ({
        ...kp,
        nx: ((kp.x - minX) / (maxX - minX)) * canvas.width,
        ny: ((kp.y - minY) / (maxY - minY)) * canvas.height
      }));
    };

    const normalizedKeypoints = normalizeCoords(keypoints);

    normalizedKeypoints.forEach((kp) => {
      if (kp.score > 0.5) {
        console.log(`Drawing point: (${kp.nx}, ${kp.ny}) with score ${kp.score}`);

        // Dibujar punto
        ctx.beginPath();
        ctx.arc(kp.nx, kp.ny, 5, 0, 2 * Math.PI);
        ctx.fillStyle = 'red';
        ctx.fill();
      }
    });

    // Dibujar conexiones entre keypoints
    const connections = [
      [0, 1],
      [0, 2],
      [1, 3],
      [2, 4],
      [0, 5],
      [0, 6],
      [5, 7],
      [7, 9],
      [6, 8],
      [8, 10],
      [5, 6],
      [5, 11],
      [6, 12],
      [11, 12],
      [11, 13],
      [13, 15],
      [12, 14],
      [14, 16]
    ];

    connections.forEach(([startIdx, endIdx]) => {
      const start = normalizedKeypoints[startIdx];
      const end = normalizedKeypoints[endIdx];

      if (start.score > 0.5 && end.score > 0.5) {
        ctx.beginPath();
        ctx.moveTo(start.nx, start.ny);
        ctx.lineTo(end.nx, end.ny);
        ctx.strokeStyle = 'green';
        ctx.lineWidth = 2;
        ctx.stroke();
      }
    });
  };

  return (
    <Box sx={{ display: 'flex', flexDirection: 'column', backgroundColor: theme.palette.grey[100], height: '100vh' }}>
      <AppContentHeader />
      <Box sx={{ flexGrow: 1, overflowY: 'auto', padding: 2 }}>
        <Grid container spacing={2}>
          <Grid item xs={12} sm={6}>
            <Paper sx={{ padding: 2, gap: 2, display: 'flex' }}>
              <Grid item xs={6}>
                <ModelViewer />
              </Grid>
              <Grid item xs={6}>
                <canvas ref={canvasGuiaRef} />
              </Grid>
            </Paper>
          </Grid>
          <Grid item xs={12} sm={6}>
            <Paper sx={{ padding: 2, position: 'relative' }}>
              {viewCameraList && (
                <Paper sx={{ padding: 2, position: 'absolute', left: 4, top: 4, zIndex: 500 }}>
                  <Typography variant="h4" gutterBottom>
                    Seleccione su Cámara
                  </Typography>
                  {videoDevices.length > 1 && (
                    <Select value={selectedDeviceId} onChange={(e) => handleCameraChange(e.target.value)} sx={{ mb: 2, width: '300px' }}>
                      {videoDevices.map((device) => (
                        <MenuItem key={device.deviceId} value={device.deviceId}>
                          {device.label || `Cámara ${device.deviceId}`}
                        </MenuItem>
                      ))}
                    </Select>
                  )}
                </Paper>
              )}
              <Button
                variant="contained"
                color="secondary"
                sx={{ position: 'absolute', right: 16, top: 16, zIndex: 500 }}
                onClick={() => setViewCameraList(!viewCameraList)}
              >
                <Cameraswitch />
              </Button>
              <Box sx={{ position: 'relative' }}>
                <Webcam
                  ref={webcamRef}
                  audio={false}
                  screenshotFormat="image/jpeg" // Necesario para getScreenshot()
                  style={{
                    width: '100%'
                  }}
                  videoConstraints={{ deviceId: selectedDeviceId ? { exact: selectedDeviceId } : undefined }} // Cámara seleccionada
                />
                <canvas
                  ref={canvasRef}
                  style={{
                    position: 'absolute',
                    top: 0,
                    left: 0,
                    width: '100%',
                    height: '100%',
                    pointerEvents: 'none'
                  }}
                />
              </Box>
              <Box sx={{ display: 'flex', justifyContent: 'center', mt: 2 }}>
                <Button variant={isDetecting ? 'contained' : 'outlined'} color="primary" onClick={toggleDetection} disabled={isLoading}>
                  {isDetecting ? 'Detener Detección' : 'Iniciar Detección'}
                </Button>
                {isLoading && <CircularProgress size={24} sx={{ ml: 2 }} />}
              </Box>
              <Typography variant="body1" sx={{ color: theme.palette.secondary.main, display: 'flex', justifyContent: 'center', mt: 1 }}>
                {status}
              </Typography>
            </Paper>
          </Grid>
          {/* Add Stepper */}
          <Box sx={{ width: '100%', padding: 2 }}>
            <Stepper activeStep={activeStep} alternativeLabel>
              {steps.map((label) => (
                <Step key={label}>
                  <StepLabel>{label}</StepLabel>
                </Step>
              ))}
            </Stepper>
          </Box>
          <Button fullWidth onClick={() => setActiveStep(activeStep + 1)}>
            SIGUIENTE
          </Button>
        </Grid>
      </Box>
    </Box>
  );
};

export default PoseDetectionScreen;
